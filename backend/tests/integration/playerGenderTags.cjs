const assert = require('node:assert/strict');
module.exports = async ({ t, pool, call, players, settings, create, member, get, adminGet, save, submit, review, current, admin, season }) => {
  await t.test('注册必填性别；旧账号补填一次，锁定后仅管理员凭原因修改并保留记录', async () => {
    const input = { student_id: 'GENDER-VALIDATE', name: '性别校验', college: '土木工程学院', password: 'Gender!Test2026', password_confirm: 'Gender!Test2026' };
    await call('/api/player/register', input, null, 'POST', null, 400);
    await call('/api/player/register', { ...input, gender: 'unknown' }, null, 'POST', null, 400);
    await call('/api/player/register', { ...input, gender: 'female' }, null, 'POST', null, 201);
    await pool.execute('UPDATE player_accounts SET gender=NULL WHERE id=?', [players[3].id]);
    const old = await call('/api/player/login', { student_id: players[3].student_id, password: 'AutoReview!2026' }, null, 'POST');
    assert.equal(old.gender, null);
    const first = await call('/api/player/me/gender', { gender: 'female' }, old.token, 'PUT', old.revision);
    assert.equal(first.gender, 'female');
    await call('/api/player/me/gender', { gender: 'male' }, old.token, 'PUT', first.revision, 409);
    await call('/api/player/me', { name: first.name, gender: 'male' }, old.token, 'PUT', first.revision, 400);
    await call('/api/player-admin/' + old.id + '/gender', { gender: 'male', reason: '越权' }, old.token, 'PUT', first.revision, 403);
    await call('/api/player-admin/' + old.id + '/gender', { gender: 'male', reason: '' }, admin, 'PUT', first.revision, 400);
    const changed = await call('/api/player-admin/' + old.id + '/gender', { gender: 'male', reason: '本人申请，经核实纠正' }, admin, 'PUT', first.revision);
    assert.equal(changed.gender, 'male');
    const history = await call('/api/player-admin/' + old.id);
    assert.equal(history.history[0].before_snapshot.gender, 'female');
    assert.equal(history.history[0].after_snapshot.gender, 'male');
  });
  await t.test('名单缺性别阻止普通提交和人工申请；标签合并去重，人工通过保留完整失败依据', async () => {
    await settings({ enable_sports_training: false, enable_football_specialty: true, max_football_specialty_players: 2, combined_player_limits: [{ tags: ['foreign', 'football_specialty'], max: 2 }] });
    await create('性别与合并限制验收队', 0, [member(1, { is_foreign: true, is_football_specialty: true, is_sports_training: true }), member(3, { is_football_specialty: true })]);
    await pool.execute('UPDATE player_accounts SET gender=NULL WHERE id=?', [players[3].id]);
    let app = await get();
    await call(`/api/player/team-applications/${app.application.id}/submit`, {}, players[0].token, 'POST', app.application.revision, 400);
    assert.equal((await get()).application.status, 'draft');
    const p = await call('/api/player/me', undefined, players[3].token);
    await call('/api/player/me/gender', { gender: 'female' }, players[3].token, 'PUT', p.revision);
    await submit(); app = current(); assert.equal(app.application.status, 'pending');
    assert.equal(app.auto_review.checks.find(c => c.tags).actual, 2);
    await call(`/api/player/team-applications/${app.application.id}/withdraw`, {}, players[0].token, 'POST', app.application.revision);
    await settings({ enable_sports_training: false, enable_football_specialty: true, combined_player_limits: [{ tags: ['foreign', 'football_specialty'], max: 1 }] });
    // Refresh the revision held by the original test helpers before submission.
    await save({ team_name: app.application.team_name, members: app.members.map(m => ({ id: m.id, player_id: m.player_id, jersey_number: m.jersey_number, is_captain: m.is_captain, is_goalkeeper: m.is_goalkeeper, is_foreign: m.is_foreign, is_sports_training: false, is_football_specialty: m.is_football_specialty })) }, true);
    await submit(); app = current(); assert.equal(app.application.status, 'auto_failed');
    const id = app.application.id;
    await pool.execute('UPDATE player_accounts SET gender=NULL WHERE id=?', [players[3].id]);
    await call(`/api/player/team-applications/${id}/submit-manual`, {}, players[0].token, 'POST', app.application.revision, 400);
    const again = await call('/api/player/me', undefined, players[3].token);
    await call('/api/player/me/gender', { gender: 'female' }, players[3].token, 'PUT', again.revision);
    await call(`/api/player/team-applications/${id}/submit-manual`, {}, players[3].token, 'POST', app.application.revision, 403);
    const manual = await call(`/api/player/team-applications/${id}/submit-manual`, {}, players[0].token, 'POST', app.application.revision);
    assert.equal(manual.application.status, 'pending'); assert.equal(manual.auto_review.manual_requested, true); assert.equal(manual.auto_review.passed, false);
    await call(`/api/player/team-applications/${id}/submit-manual`, {}, players[0].token, 'POST', app.application.revision, 409);
    await review('override-approve', { reason: '组委会同意合并人数特例' });
    app = current(); assert.equal(app.application.status, 'approved'); assert.equal(app.auto_review.override.failed_review.manual_requested, true);
    const publicTeam = await call('/api/public/teams/' + app.application.team_id, undefined, null);
    assert.equal(publicTeam.players.filter(p => p.is_football_specialty).length, 2);
    assert.equal(publicTeam.players.some(p => p.is_sports_training), false);
    await settings({ enable_sports_training: false, enable_football_specialty: false });
    const hidden = await adminGet();
    assert.equal(JSON.stringify(hidden).includes('足球特长生'), false);
    assert.equal(hidden.members.some(p => p.is_football_specialty), false);
    const publicHidden = await call('/api/public/teams/' + app.application.team_id, undefined, null);
    assert.equal(publicHidden.players.some(p => p.is_football_specialty), false);
    const roster = await call('/api/team/' + app.application.team_id + '/current-roster');
    assert.equal(roster.players.some(p => p.is_football_specialty), false);
    const [[stored]] = await pool.execute('SELECT COUNT(*) n FROM team_player WHERE team_id=? AND is_football_specialty=1', [app.application.team_id]);
    assert.equal(stored.n, 2);
    await settings({ enable_sports_training: false, enable_football_specialty: true });
    assert.equal((await call('/api/public/teams/' + app.application.team_id, undefined, null)).players.filter(p => p.is_football_specialty).length, 2);
    const formal = await call('/api/player/teams/' + app.application.team_id, undefined, players[0].token);
    let change = await call(`/api/player/teams/${formal.team.id}/roster-changes`, {}, players[0].token, 'POST', formal.team.revision, 201, { 'Idempotency-Key': require('node:crypto').randomUUID() });
    assert.equal(change.members.filter(p => p.is_football_specialty).length, 2);
    change = await call(`/api/player/team-applications/${change.application.id}/submit`, {}, players[0].token, 'POST', change.application.revision);
    const check = await adminGet(change.application.id);
    await call(`/api/player-admin/team-applications/${change.application.id}/approve`, { review_token: check.review_token }, admin, 'POST', check.application.revision);
    assert.equal((await call('/api/public/teams/' + formal.team.id, undefined, null)).players.filter(p => p.is_football_specialty).length, 2);
  });
  await t.test('0030重复迁移保留性别、账号、标签与审核证据', async () => {
    const tables = ['player_accounts', 'team_applications', 'team_application_members', 'team_application_events', 'team_player', 'season_competitions'];
    const before = {};
    for (const table of tables) before[table] = (await pool.query('SELECT * FROM ' + table + ' ORDER BY id'))[0];
    const c = await pool.getConnection();
    try { await require('../../../db/migrations/0030_player_gender_and_team_tags').up(c); } finally { c.release(); }
    for (const table of tables) assert.deepEqual((await pool.query('SELECT * FROM ' + table + ' ORDER BY id'))[0], before[table]);
  });
};
