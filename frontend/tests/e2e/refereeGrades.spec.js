import { test, expect } from '@playwright/test'

const password = process.env.E2E_PASSWORD
const grades = ['裁判学员', '三级', '二级', '一级', '预备国家级', '国家级']
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jF1sAAAAASUVORK5CYII=', 'base64')
async function login(page, admin = false) {
  await page.goto(admin ? '/admin-login' : '/referee-login')
  await page.getByPlaceholder(admin ? '请输入用户名' : '请输入学号').fill(admin ? 'e2e-admin' : 'E2E-20')
  await page.getByPlaceholder('请输入密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(admin ? '/admin-dashboard$' : '/referee-dashboard$'))
}

test('注册页六级选项顺序一致，学员可不填日期完成注册', async ({ page }) => {
  await page.goto('/referee-register')
  await page.getByPlaceholder('请输入学号').fill('E2E-NEW-TRAINEE')
  await page.getByPlaceholder('请输入姓名').fill('浏览器新学员')
  await page.getByLabel('学院', { exact: true }).selectOption('土木工程学院')
  const selects = page.locator('.referee-form select')
  await selects.nth(0).selectOption('男')
  for (const index of [2, 3]) {
    await expect(selects.nth(index).locator('option')).toHaveText(['-- 请选择 --', ...grades])
    await selects.nth(index).selectOption('裁判学员')
  }
  await expect(page.locator('input[type=date]')).not.toHaveAttribute('required')
  await selects.nth(2).selectOption('三级')
  await expect(page.locator('input[type=date]')).toHaveAttribute('required', '')
  await selects.nth(2).selectOption('裁判学员')
  await selects.nth(4).selectOption('false')
  await page.locator('input[type=number]').nth(0).fill('175')
  await page.locator('input[type=number]').nth(1).fill('65')
  await page.getByLabel('院内赛', { exact: true }).check()
  await page.locator('input[type=file]').setInputFiles({ name: 'trainee.png', mimeType: 'image/png', buffer: png })
  await page.locator('input[type=password]').nth(0).fill(password)
  await page.locator('input[type=password]').nth(1).fill(password)
  const saved = page.waitForResponse(r => r.url().endsWith('/api/referee/register') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '注册', exact: true }).click()
  expect((await saved).status()).toBe(201)
})

test('裁判设置随时修改，学员空日期保存及晋级日期校验，失败保留输入，手机可用', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const form = page.locator('.grade-settings')
  await expect(form.getByLabel('当前级别', { exact: true })).toHaveValue('三级')
  await expect(form.locator('option')).toHaveText(grades)
  await form.getByLabel('当前级别', { exact: true }).selectOption('裁判学员')
  await form.locator('input[type=date]').fill('')
  await form.getByRole('button', { name: '保存当前级别' }).click()
  await expect(form.getByRole('status')).toContainText('已保存')
  await page.locator('.close-btn').click()
  await expect(page.locator('.stat-hint')).toContainText('裁判学员')
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(form.getByLabel('当前级别', { exact: true })).toHaveValue('裁判学员')
  await expect(form.locator('input[type=date]')).toHaveValue('')
  await form.getByLabel('当前级别', { exact: true }).selectOption('三级')
  await expect(form.locator('input[type=date]')).toHaveAttribute('required', '')
  await form.getByRole('button', { name: '保存当前级别' }).click()
  await expect(form.locator('input:invalid')).toHaveCount(1)
  await form.locator('input[type=date]').fill('2026-09-28')
  await page.route('**/api/referee/*/grade', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: '测试网络中断' }) }))
  await form.getByRole('button', { name: '保存当前级别' }).click()
  await expect(form.getByRole('alert')).toContainText('测试网络中断')
  await expect(form.locator('input[type=date]')).toHaveValue('2026-09-28')
  await expect(page.locator('.stat-hint')).toContainText('裁判学员')
  await page.unroute('**/api/referee/*/grade')
  await form.getByRole('button', { name: '保存当前级别' }).click()
  await expect(form.getByRole('status')).toContainText('已保存')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.modal-content').evaluate(element => { element.scrollTop = 0 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: 'test-results/trainee-settings-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.modal-content').evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: 'test-results/trainee-settings-desktop.png' })
  await page.locator('.close-btn').click()
  await expect(page.locator('.stat-hint')).toContainText('三级')
  expect(errors).toEqual([])
})

test('管理员新增及编辑学员，赛季审核筛选均有六级选项', async ({ page }) => {
  await login(page, true)
  await page.goto('/admin-referees')
  await page.getByRole('button', { name: '新增裁判账号', exact: true }).click()
  const form = page.locator('.create-form')
  await expect(form.getByRole('combobox', { name: '当前级别', exact: true }).locator('option')).toHaveText(grades)
  await expect(form.getByRole('combobox', { name: '目标级别', exact: true }).locator('option')).toHaveText(grades)
  await form.getByLabel('学号', { exact: true }).fill('E2E-ADMIN-TRAINEE')
  await form.getByLabel('姓名', { exact: true }).fill('管理端学员')
  await form.getByRole('combobox', { name: '当前级别', exact: true }).selectOption('裁判学员')
  await form.getByRole('combobox', { name: '目标级别', exact: true }).selectOption('三级')
  await form.getByLabel('学院', { exact: true }).fill('土木工程学院')
  await form.getByLabel('身高（cm）').fill('175')
  await form.getByLabel('体重（kg）').fill('65')
  await form.getByLabel('足协杯', { exact: true }).check()
  await form.getByLabel('证件照').setInputFiles({ name: 'trainee.png', mimeType: 'image/png', buffer: png })
  await form.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.locator('.alert.success')).toContainText('账号创建成功')
  await page.getByLabel('姓名或学号').fill('E2E-ADMIN-TRAINEE')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.locator('tbody').getByRole('button', { name: '详情', exact: true }).click()
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  const editor = page.locator('.editor-card')
  await expect(editor.getByRole('combobox', { name: '当前级别', exact: true })).toHaveValue('裁判学员')
  await expect(editor.locator('input[type=date]')).toHaveValue('')
  await editor.getByRole('button', { name: '保存全部资料', exact: true }).click()
  await expect(page.locator('.alert.success')).toContainText('已保存')
  await page.goto('/admin-season-registrations')
  await expect(page.locator('select').filter({ has: page.locator('option[value="裁判学员"]') }).locator('option')).toHaveText(['全部级别', ...grades])
})
