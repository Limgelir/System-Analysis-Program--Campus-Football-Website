import { test, expect } from '@playwright/test'
import { createRequire } from 'node:module'
import { readFile } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const mysql = require('../../../backend/node_modules/mysql2/promise')
const JSZip = require('../../../backend/node_modules/jszip')
let fixture
test.beforeAll(async () => {
  if (process.env.REFWEB_E2E !== '1' || !process.env.DB_NAME?.startsWith('tj_refweb_e2e_')) throw Error('仅限隔离E2E库')
  const c = await mysql.createConnection({ host: process.env.DB_HOST, port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER, password: process.env.DB_PASSWORD, database: process.env.DB_NAME })
  try { fixture = await require('../../../backend/scripts/seedFourthOfficialSheet')(c) }
  finally { await c.end() }
})
for (const mobile of [false, true]) test(`四官单选择、取消、下载与失败重试（${mobile ? '手机' : '桌面'}）`, async ({ page }) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/admin-login')
  await page.getByPlaceholder('请输入用户名').fill('e2e-admin')
  await page.getByPlaceholder('请输入密码', { exact: true }).fill(process.env.E2E_PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/admin-dashboard$/)
  await page.goto(`/admin-schedule?season_id=${fixture.seasonId}`)
  const row = page.locator('tbody tr').filter({ has: page.getByText('A01', { exact: true }) })
  const open = () => row.getByRole('button', { name: '生成四官单', exact: true }).click()
  let requests = 0
  page.on('request', request => { if (request.url().includes('/fourth-official-sheet')) requests++ })
  await open()
  const dialog = page.getByRole('dialog', { name: '生成四官单' })
  await expect(dialog).toContainText('土木工程学院 vs 机械与能源工程学院')
  await expect(dialog.getByLabel('11人制（大联赛）版本')).toBeChecked()
  await expect(dialog.getByLabel(/8人制/)).toBeEnabled()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).not.toBeVisible(); expect(requests).toBe(0)
  await open(); await page.keyboard.press('Escape'); await expect(dialog).not.toBeVisible()
  await open()
  const bounds = await dialog.boundingBox(); expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(mobile ? 390 : 1440)
  await page.screenshot({ path: `test-results/fourth-sheet-${mobile ? 'mobile' : 'desktop'}.png` })
  const downloaded = page.waitForEvent('download')
  await dialog.getByRole('button', { name: '生成并下载 Word' }).click()
  const download = await downloaded
  expect(download.suggestedFilename()).toBe('四官单-11人制-A01-土木工程学院vs机械与能源工程学院.docx')
  const zip = await JSZip.loadAsync(await readFile(await download.path()))
  const xml = await zip.file('word/document.xml').async('string')
  expect(xml).not.toContain('{{'); expect(xml.match(/<w:tbl>/g)).toHaveLength(2)
  expect(xml.match(/2026-2027同济大学足球联赛/g)).toHaveLength(2)
  expect(xml.match(/嘉定校区西侧足球场/g)).toHaveLength(2)
  expect(xml.match(/<w:t[^>]*>×<\/w:t>/g)).toHaveLength(2)
  const plain = [...xml.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g)].map(m => m[1]).join('')
  expect(plain).toContain('阿卜杜热合曼·买买提江(C)(GK)(F)(S)')
  expect(plain).toContain('Christopher Alexander Montgomery(F)(S)')
  expect(plain).not.toContain('(S)(S)')
  await expect(dialog).not.toBeVisible()
  await open()
  await page.route('**/fourth-official-sheet?*', route => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ message: '名单发生变化，请核对后重试' }) }))
  await dialog.getByRole('button', { name: '生成并下载 Word' }).click()
  await expect(dialog.getByRole('alert')).toHaveText('名单发生变化，请核对后重试')
  await expect(dialog.getByRole('button', { name: '生成并下载 Word' })).toBeEnabled()
  await page.unroute('**/fourth-official-sheet?*')
  const retry = page.waitForEvent('download'); await dialog.getByRole('button', { name: '生成并下载 Word' }).click(); await retry
  await expect(dialog).not.toBeVisible(); expect(errors).toEqual([])
  // A separate cup match has the full 17-player roster on each side.
  const cupRow = page.locator('tbody tr').filter({ has: page.getByText('B01', { exact: true }) })
  await cupRow.getByRole('button', { name: '生成四官单', exact: true }).click()
  await dialog.getByLabel('8人制（足协杯）版本').check()
  await expect(dialog).toContainText('下载一页 Word 文档')
  await page.screenshot({ path: `test-results/fourth-sheet-eight-${mobile ? 'mobile' : 'desktop'}.png` })
  const cupDownloadEvent = page.waitForEvent('download')
  await dialog.getByRole('button', { name: '生成并下载 Word' }).click()
  const cupDownload = await cupDownloadEvent
  expect(cupDownload.suggestedFilename()).toBe('四官单-8人制-B01-建筑与城市规划学院vs电子与信息工程学院.docx')
  const cupZip = await JSZip.loadAsync(await readFile(await cupDownload.path()))
  const cupXml = await cupZip.file('word/document.xml').async('string')
  const cupText = [...cupXml.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g)].map(m => m[1]).join('')
  expect(cupText).toContain('2026年同济大学秋季足协杯比赛报告表')
  expect(cupText).not.toContain('2025同济大学'); expect(cupText).not.toContain('张裁判')
  expect(cupXml).not.toContain('{{'); expect(cupXml.match(/<w:tbl>/g)).toHaveLength(2)
  expect(cupText).toContain('红/白/红'); expect(cupText).toContain('蓝/白/蓝')
  expect(cupText.match(/建筑与城市规划学院/g)).toHaveLength(1)
  expect(cupXml.match(/<w:t[^>]*>×<\/w:t>/g)).toHaveLength(2)
  expect(cupText).toContain('嘉定校区西侧足球场')
  expect(cupText).toContain('阿卜杜热合曼·买买提江(C)(GK)(F)(S)')
  expect(cupText).toContain('Christopher Alexander Montgomery(F)(S)')
  expect(cupText).not.toContain('(S)(S)')
  await expect(dialog).not.toBeVisible(); expect(errors).toEqual([])
})
