import { test, expect } from '@playwright/test'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const mysql = require('../../../backend/node_modules/mysql2/promise')

for (const mobile of [false,true]) test(`报告提交后调整选派及重合提醒（${mobile?'手机':'桌面'}）`,async({page})=>{
  test.setTimeout(90000)
  if (mobile) await page.setViewportSize({width:390,height:844})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  if(process.env.REFWEB_E2E!=='1'||!process.env.DB_NAME.startsWith('tj_refweb_e2e_'))throw Error('仅限隔离E2E库')
  const c=await mysql.createConnection({host:process.env.DB_HOST,port:Number(process.env.DB_PORT||3306),user:process.env.DB_USER,password:process.env.DB_PASSWORD,database:process.env.DB_NAME})
  let fixture
  const externalName='本地外部裁判'+(mobile?'乙':'甲')
  try {
    fixture=await require('../../../backend/scripts/seedAssignmentExport')(c,{active:true})
    await c.execute('UPDATE seasons SET season_name=? WHERE id=?',['选派交接验收'+(mobile?'手机':'桌面'),fixture.seasonId])
    await c.execute('UPDATE external_referees SET name=? WHERE id=?',[externalName,fixture.externalId])
    await c.execute('UPDATE match_official_assignments SET name_snapshot=? WHERE external_referee_id=?',[externalName,fixture.externalId])
    await c.execute("UPDATE match_schedules SET match_time='15:00',match_end_time='17:00' WHERE id=?",[fixture.matches.A01])
    await c.execute("UPDATE match_schedules SET match_time='16:00',match_end_time='18:00' WHERE id=?",[fixture.matches.A02])
    await c.execute("UPDATE match_reports SET main_report_status='submitted',supervisor_review_status='submitted',main_report_started_at=NOW(),supervisor_review_started_at=NOW(),main_report_submitted_at=NOW(),supervisor_review_submitted_at=NOW() WHERE schedule_id=?",[fixture.matches.A01])
  } finally { await c.end() }
  await page.goto('/admin-login')
  await page.getByPlaceholder('请输入用户名').fill('e2e-admin')
  await page.getByPlaceholder('请输入密码',{exact:true}).fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page).toHaveURL(/admin-dashboard$/)
  await page.goto(`/admin-assignments?view=all&season_id=${fixture.seasonId}`)
  const editor=page.locator('#match-'+fixture.matches.A01)
  await expect(editor.getByLabel('五人制裁判安排')).toBeEnabled()
  await expect(editor.getByLabel('本场需要裁判监督')).toBeEnabled()
  await expect(editor.getByRole('button',{name:'保存选派',exact:true})).toBeEnabled()
  const pick=async(role,name)=>{
    const input=editor.getByPlaceholder('搜索'+role+'姓名或学号',{exact:true})
    await input.fill(name)
    await editor.locator('.result-item').filter({has:page.locator('strong',{hasText:name})}).first().click()
  }
  await pick('裁判员',externalName)
  await expect(editor.locator('.assignment-warnings')).toContainText(externalName+'裁判员同时已经在')
  await expect(editor.locator('.assignment-warnings')).toContainText('场序 A02')
  let dialogs=0
  page.on('dialog',async d=>{dialogs++;await d.accept()})
  const saved=page.waitForResponse(r=>r.url().endsWith('/assign-referees')&&r.request().method()==='PUT')
  await editor.getByRole('button',{name:'保存选派',exact:true}).click()
  const payload=await (await saved).json()
  expect(payload.success).toBe(true)
  expect(payload.data.report_main_status).toBe('returned')
  expect(payload.data.report_supervisor_status).toBe('returned')
  await expect(editor.getByText('选派已保存',{exact:true})).toBeVisible()
  expect(dialogs).toBe(0)
  await expect(editor.locator('.assignment-warnings')).toContainText('仍可保存')
  await editor.scrollIntoViewIfNeeded()
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  await page.screenshot({path:`test-results/assignment-changes-${mobile?'mobile':'desktop'}.png`,fullPage:false})
  await editor.getByLabel('本场需要第四官员').uncheck()
  await editor.getByLabel('本场需要裁判监督').uncheck()
  await editor.getByLabel('五人制裁判安排').check()
  await pick('第二裁判员','李助理');await pick('计时员','王助理')
  const changed=page.waitForResponse(r=>r.url().endsWith('/assign-referees')&&r.request().method()==='PUT')
  await editor.getByRole('button',{name:'保存选派',exact:true}).click()
  const next=await (await changed).json();expect(next.success).toBe(true)
  expect(next.data.futsal).toBe(true);expect(next.data.supervisor_required).toBe(false)
  expect(next.data.officials.map(a=>a.role).sort()).toEqual(['main','second','timekeeper'])
  expect(dialogs).toBe(1)
  await page.reload()
  await expect(editor.getByLabel('五人制裁判安排')).toBeChecked()
  await expect(editor.getByPlaceholder('搜索第二裁判员姓名或学号')).toBeEnabled()
  expect(errors).toEqual([])
})
