import {test,expect} from '@playwright/test'
import {createRequire} from 'node:module'
const require=createRequire(import.meta.url)
const seed=require('../../../backend/scripts/seedAdminTeamManagement')
for(const mobile of [false,true])test(`管理员球队编辑及误操作恢复（${mobile?'手机':'桌面'}）`,async({page})=>{
  test.setTimeout(120000)
  if(mobile)await page.setViewportSize({width:390,height:844})
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept())
  const suffix=mobile?'MOBILE':'DESKTOP'
  const fixture=await seed({base:process.env.E2E_BASE_URL,username:'e2e-admin',password:process.env.E2E_PASSWORD,suffix})
  await page.goto('/admin-login');await page.getByPlaceholder('请输入用户名').fill('e2e-admin');await page.getByPlaceholder('请输入密码',{exact:true}).fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page).toHaveURL(/admin-dashboard$/)
  await page.goto('/admin-teams');await page.getByRole('button',{name:/可编辑示例队/}).click()
  const editor=page.locator('.team-editor');await editor.getByRole('button',{name:'打开编辑',exact:true}).click()
  await expect(editor).toContainText('不受报名或名单修改时间、赛事自动审核及球员资格限制')
  await editor.getByLabel('球队名称',{exact:true}).fill('本地验收改名成功')
  await editor.getByLabel('新负责人学号').fill(`ADM-${suffix}-3`);await editor.getByRole('button',{name:'核对并选择负责人'}).click()
  await expect(editor.getByText(`负责人：新负责人丙 · ADM-${suffix}-3`,{exact:true})).toBeVisible()
  await editor.getByLabel('队长甲号码',{exact:true}).fill('11')
  await editor.getByRole('button',{name:'移除队员乙',exact:true}).click()
  await editor.getByLabel('添加球员学号').fill(`ADM-${suffix}-4`);await editor.getByRole('button',{name:'按学号添加球员'}).click()
  await expect(editor).toContainText('账号已停用')
  await editor.getByLabel('候补丁号码',{exact:true}).fill('11')
  await editor.getByRole('button',{name:'保存球队修改（立即生效）'}).click()
  await expect(editor.getByRole('alert')).toContainText('同队号码不能重复')
  await editor.getByLabel('候补丁号码',{exact:true}).fill('22');await editor.getByRole('button',{name:'保存球队修改（立即生效）'}).click()
  await expect(editor.getByRole('status')).toContainText('立即生效')
  await expect(page.locator('.team-detail-name')).toHaveText('本地验收改名成功')
  await expect(page.locator('.team-item.active')).toContainText('本地验收改名成功')
  await expect(editor.getByLabel('队长甲号码',{exact:true})).toHaveValue('11')
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  await page.screenshot({path:`test-results/admin-team-${suffix.toLowerCase()}.png`,fullPage:true})
  await editor.screenshot({path:`test-results/admin-team-editor-${suffix.toLowerCase()}.png`})
  await page.getByRole('button',{name:/四学院超限验收队/}).click();await editor.getByRole('button',{name:'打开编辑',exact:true}).click()
  await editor.getByLabel('上衣主要颜色',{exact:true}).fill('四学院仍可保存')
  await editor.getByLabel('添加球员学号').fill(`ADM-${suffix}-0`);await editor.getByRole('button',{name:'按学号添加球员'}).click()
  const unqualified=editor.locator('.editor-member').filter({hasText:`原负责人 · ADM-${suffix}-0`})
  await expect(unqualified).toContainText('学籍未通过');await editor.getByLabel('原负责人号码',{exact:true}).fill('77')
  await unqualified.getByLabel('外援',{exact:true}).check();await unqualified.getByLabel('运训',{exact:true}).check();await unqualified.getByLabel('足球特长生',{exact:true}).check()
  await editor.getByRole('button',{name:'保存球队修改（立即生效）'}).click();await expect(editor.getByRole('status')).toContainText('立即生效')
  await page.reload();await page.getByRole('button',{name:/四学院超限验收队/}).click();await editor.getByRole('button',{name:'打开编辑',exact:true}).click()
  await expect(editor.getByLabel('上衣主要颜色',{exact:true})).toHaveValue('四学院仍可保存');await expect(editor).toContainText('当前编辑名单：5 人')
  await expect(editor.getByRole('alert')).toHaveCount(0)
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  await editor.screenshot({path:`test-results/admin-team-exemption-${suffix.toLowerCase()}.png`})
  await page.goto('/admin-schedule');await expect(page.getByRole('cell').filter({hasText:'本地验收改名成功 vs 赛程对手队'})).toBeVisible()
  await page.goto('/admin-team-applications')
  await page.getByRole('row').filter({hasText:'可撤销退回队'}).getByRole('button',{name:'查看球队申请'}).click()
  await page.getByRole('button',{name:'撤销退回球队补正',exact:true}).click();await expect(page.getByRole('status')).toContainText('已撤销退回')
  await expect(page.locator('.team-review-detail')).toContainText('状态：待审核')
  await page.getByRole('row').filter({hasText:'可恢复通过队'}).getByRole('button',{name:'查看球队申请'}).click()
  await page.getByRole('button',{name:'撤销撤销报名通过（恢复通过）',exact:true}).click();await expect(page.getByRole('status')).toContainText('已恢复报名通过')
  await expect(page.locator('.team-review-detail')).toContainText('状态：已通过')
  await page.screenshot({path:`test-results/admin-team-undo-${suffix.toLowerCase()}.png`,fullPage:true})
  expect(errors).toEqual([])
})
