// 仅生成配置，不修改本机 Nginx、DNS 或证书。bootstrap 阶段不开放 HTTP 登录。
const fs = require('node:fs');
const path = require('node:path');
const defaults = require('./sites.example.json');

function quote(value) {
  if (typeof value !== 'string' || !path.isAbsolute(value) || /[\x00-\x1f";$`{}]/.test(value)) {
    throw new Error('目录和证书必须为不含配置控制字符的绝对路径');
  }
  return `"${value.replace(/\\/g, '/')}"`;
}
function validate(options = {}) {
  for (const key of Object.keys(options)) if (!(key in defaults) && key !== 'loopback') throw new Error(`未知站点配置: ${key}`);
  const c = { ...defaults, ...options };
  if (!Array.isArray(c.refereeAliases)) throw new Error('refereeAliases 必须为域名数组');
  const domains = [c.refereeDomain, c.playerDomain, ...c.refereeAliases];
  for (const domain of domains) {
    if (typeof domain !== 'string' || domain.length > 253 || !/^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/.test(domain)) throw new Error('无效域名');
  }
  if (new Set(domains).size !== domains.length) throw new Error('入口和别名必须使用不同域名');
  for (const key of ['refereeRoot', 'playerRoot', 'acmeRoot', 'certificate', 'certificateKey', 'logRoot']) quote(c[key]);
  if (c.refereeRoot === c.playerRoot) throw new Error('两个静态目录不能相同');
  const ports = [c.httpPort, c.httpsPort, c.backendPort];
  if (ports.some(p => !Number.isInteger(p) || p < 1 || p > 65535) || new Set(ports).size !== 3) throw new Error('端口必须合法且互不相同');
  if (c.loopback !== undefined && typeof c.loopback !== 'boolean') throw new Error('loopback 必须为布尔值');
  return c;
}
function render(options = {}, mode = 'https') {
  if (!['bootstrap', 'https'].includes(mode)) throw new Error('模式只能是 bootstrap 或 https');
  const c = validate(options), bind = c.loopback ? '127.0.0.1:' : '';
  const headers = `    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
    add_header Content-Security-Policy "default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; form-action 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' blob: data:; font-src 'self' data:; connect-src 'self'" always;
    add_header Strict-Transport-Security "max-age=86400" always;
    add_header X-Request-ID $request_id always;`;
  const proxy = (location, upstream) => `    location ${location} {
        proxy_pass http://127.0.0.1:${c.backendPort}${upstream};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Request-ID $request_id;
        proxy_hide_header X-Request-ID;
        proxy_connect_timeout 5s;
        proxy_read_timeout 60s;
    }`;
  let config = `# Generated by deploy/renderProduction.js; loaded inside nginx http {}.
# 不记录 URI、查询参数、Referer、Authorization、Cookie 或请求内容。
log_format refweb_json escape=json '{"time":"$time_iso8601","channel":"edge","request_id":"$request_id","site":"$server_name","method":"$request_method","status":$status,"bytes":$body_bytes_sent,"duration":$request_time}';
access_log ${quote(path.join(c.logRoot, 'access.log'))} refweb_json;
error_log ${quote(path.join(c.logRoot, 'error.log'))} crit;
server {
    listen ${bind}${c.httpPort} default_server;
    server_name _;
    return 444;
}
`;
  if (mode === 'https') config += `server {
    listen ${bind}${c.httpsPort} ssl default_server;
    ssl_reject_handshake on;
    server_name _;
    return 444;
}
`;
  for (const [domain, root] of [[c.refereeDomain, c.refereeRoot], [c.playerDomain, c.playerRoot], ...c.refereeAliases.map(d => [d, null])]) {
    config += `server {
    listen ${bind}${c.httpPort};
    server_name ${domain};
    server_tokens off;
    location ^~ /.well-known/acme-challenge/ {
        root ${quote(c.acmeRoot)};
        default_type text/plain;
        try_files $uri =404;
    }
    location / { ${mode === 'bootstrap' ? 'return 503;' : `return 308 https://${root ? domain : c.refereeDomain}${c.httpsPort === 443 ? '' : ':' + c.httpsPort}$request_uri;`} }
}
`;
    if (mode === 'bootstrap') continue;
    if (!root) {
      config += `server {
    listen ${bind}${c.httpsPort} ssl;
    server_name ${domain};
    ssl_certificate ${quote(c.certificate)};
    ssl_certificate_key ${quote(c.certificateKey)};
    ssl_protocols TLSv1.2 TLSv1.3;
    server_tokens off;
    return 308 https://${c.refereeDomain}${c.httpsPort === 443 ? '' : ':' + c.httpsPort}$request_uri;
}\n`;
      continue;
    }
    config += `server {
    listen ${bind}${c.httpsPort} ssl;
    server_name ${domain};
    ssl_certificate ${quote(c.certificate)};
    ssl_certificate_key ${quote(c.certificateKey)};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:REFWEB:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;
    root ${quote(root)};
    index index.html;
    server_tokens off;
    client_max_body_size 11m;
    gzip on;
    gzip_min_length 1024;
    gzip_vary on;
    gzip_types text/css application/javascript application/json image/svg+xml;
${headers}
    location = /api { return 404; }
${proxy('/api/', '')}
${proxy('= /health', '/health')}
${proxy('= /health/live', '/health/live')}
    location ~ (^|/)\\. { return 404; }
    location ~* \\.(seed|sql|env|bak|log)$ { return 404; }
    location /uploads/ { return 404; }
    location /assets/ { try_files $uri =404; expires 7d; }
    location / { try_files $uri $uri/ /index.html; expires -1; }
}
`;
  }
  return config;
}
if (require.main === module) {
  try {
    const args = {};
    for (const arg of process.argv.slice(2)) {
      const match = /^--(config|mode|output)=(.+)$/.exec(arg);
      if (!match || args[match[1]]) throw new Error('参数: --config=站点JSON --mode=bootstrap|https --output=新文件');
      args[match[1]] = match[2];
    }
    const config = render(args.config ? JSON.parse(fs.readFileSync(args.config, 'utf8')) : {}, args.mode);
    if (args.output) fs.writeFileSync(args.output, config, { flag: 'wx', mode: 0o600 });
    else process.stdout.write(config);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { render, validate };
